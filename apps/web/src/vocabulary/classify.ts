function wordKey(value: string): string {
  return value.trim().toLocaleLowerCase().replace(/^(en|ett)\s+/u, '');
}

/** A known preschool word, or null when the labels do not decide a category. */
export function categoryFromWords(zh: string, sv: string): VocabularyCategoryId | null {
  return WORDS[zh.trim()] ?? WORDS[wordKey(sv)] ?? null;
}

export function categoryIsManual(card: { category?: string | null; categorySource?: string | null }): boolean {
  if (card.categorySource === 'manual') return true;
  if (card.categorySource === 'auto' || card.categorySource === 'unset') return false;
  const known = vocabularyCategory(card.category).id;
  return Boolean(card.category) && known !== 'other';
}

/**
 * Category to store for an old card. Null means leave the card alone.
 * A parent's choice is never replaced.
 */
export function migratedCategory(card: { zh: string; sv: string; category?: string | null; categorySource?: string | null }): VocabularyCategoryId | null {
  if (categoryIsManual(card)) return null;
  if (card.categorySource === 'auto') return null;
  const mapped = categoryFromWords(card.zh, card.sv);
  if (!mapped) return null;
  if (vocabularyCategory(card.category).id === mapped && card.category) return null;
  return mapped;
}
